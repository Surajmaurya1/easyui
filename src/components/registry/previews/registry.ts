// Fast lookup map supporting both primary slugs and aliases
const ALIAS_MAP = new Map<string, string>();
for (const [id, def] of Object.entries(PREVIEW_REGISTRY)) {
  ALIAS_MAP.set(id, id);
  if (def.aliases) {
    for (const alias of def.aliases) {
      ALIAS_MAP.set(alias, id);
    }
  }
}

export function getComponentPreview(idOrSlug: string): ComponentPreviewDefinition | undefined {
  const targetId = ALIAS_MAP.get(idOrSlug) || idOrSlug;
  return PREVIEW_REGISTRY[targetId];
}
